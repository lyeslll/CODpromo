// ============================================================
//  BidiText — نص عربي فيه كلمات لاتينية (أسماء الشركات، الأكواد…) ومبالغ بعملة
//  في الصفحات العربية (RTL) كل سلسلة لاتينية تتعزل في <bdi> باش ما تتلخبطش الرموز حولها:
//  مثلاً "لأعضاء CODpromo Premium!" كانت تبان "!CODpromo Premium" — دروك علامة التعجب
//  تبقى مع الكلمة اللاتينية اللي قبلها. نفس الشي للمبالغ والنسب ("5$"، "$5"، "10%"): كي يجي الرقم
//  بعد حرف عربي الـ $ ولا % كانو يقفزو للجهة الأخرى ("بـ $2" بلاصة "بـ 2$").
// ============================================================

// كلمة لاتينية، حتى بالحروف المنبّرة (Algérie، Sénégal)، (+ أرقام ورموز داخلية: Just.Sell، Voice213، e-commerce) + كلمات بعدها + ! أو ? في الآخر،
// ولا مبلغ / نسبة: "$5"، "5$"، "10%"، "5 €".
const RUN = new RegExp(
  "(" +
    "[A-Za-zÀ-ÖØ-öø-ſ][A-Za-zÀ-ÖØ-öø-ſ0-9]*(?:[.&+'’_-][A-Za-zÀ-ÖØ-öø-ſ0-9]+)*(?:[ \\u00A0]+[A-Za-zÀ-ÖØ-öø-ſ0-9][A-Za-zÀ-ÖØ-öø-ſ0-9]*(?:[.&+'’_-][A-Za-zÀ-ÖØ-öø-ſ0-9]+)*)*[!?]*" +
    "|\\$\\s?\\d[\\d.,]*" +
    "|\\d[\\d.,]*\\s?[$%€]" +
    ")",
  "g"
);

export function bidiParts(text) {
  return String(text ?? "").split(RUN);
}

export default function BidiText({ text, rtl = true }) {
  if (text == null || text === "") return null;
  if (!rtl) return text;
  const parts = bidiParts(text);
  if (parts.length === 1) return text;
  return parts.map((p, i) => (i % 2 ? <bdi key={i} dir="ltr">{p}</bdi> : p || null));
}
